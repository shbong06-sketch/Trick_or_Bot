# TrickOrBot 구현 지침 v2
# [공통 구현 원칙]
# - 아래 내용은 구현할 기능의 설명이며, 현재 기능이 구현되어 있다는 뜻은 아니다.
# - ROS 2 Jazzy와 현재 패키지 구조를 기준으로 최소한의 구현을 작성한다.
# - docs/interfaces.md와 관련 .msg/.srv 파일을 확인하고 공통 규격을 따른다.
# - 필수 규격이나 게임 규칙이 미정이면 필요한 결정 사항을 먼저 명시한다.
# - 미정인 값을 실제 장비에서 확인한 값처럼 사용하지 않는다.
# - 기존 ROS/Nav2 기능과 공통 모듈을 재사용하고 같은 기능을 중복 구현하지 않는다.
# - 요청하지 않은 패키지, 외부 서버, DB, 플러그인 구조는 추가하지 않는다.
# - 단순한 기능을 불필요한 클래스 계층이나 여러 보조 파일로 나누지 않는다.
# - 필요한 입력 검사와 안전 처리는 구현하되 자동 복구 기능을 임의로 확대하지 않는다.
# - 이 파일의 완료 기준을 만족하면 추가 기능 구현을 멈춘다.
#
# [역할]
# 고정 웹캠의 픽셀과 지도 좌표 사이 호모그래피를 계산하는 보정 도구.
# [입출력]
# 입력: 카메라 영상의 기준점과 대응하는 지도 기준점.
# 출력: camera_mapping.yaml 형식의 보정 정보.
# [구현]
# OpenCV의 기존 함수를 사용하고 해상도·카메라 ID·기준점·변환을 저장한다.
# 기준점 배치와 계산 결과가 유효한지 검사한다.
# 보정에 사용하지 않은 검증점에서 오차를 확인할 수 있게 한다.
# [실패 처리]
# 점 부족·잘못된 배치·비정상 변환은 저장하지 않고 원인을 알린다.
# 기존 보정 파일을 덮어쓸 때는 저장 경로와 처리 방식을 명시한다.
# [범위]
# 단순한 점 선택과 좌표 입력으로 시작한다.
# 자동 마커 지도 작성, 전용 웹 UI, 실시간 자동 보정 시스템은 만들지 않는다.
# [완료 기준]
# 저장 파일을 webcam_localizer가 읽을 수 있고 검증점 오차를 확인할 수 있다.
