# TrickOrBot 구현 지침 v2
# [공통 구현 원칙]
# - 아래 내용은 구현할 기능의 설명이며, 현재 기능이 구현되어 있다는 뜻은 아니다.
# - ROS 2 Jazzy와 현재 패키지 구조를 기준으로 최소한의 구현을 작성한다.
# - docs/interfaces.md와 관련 .msg/.srv 파일을 확인하고 공통 규격을 따른다.
# - 필수 규격이나 게임 규칙이 미정이면 필요한 결정 사항을 먼저 명시한다.
# - 미정인 값을 실제 장비에서 확인한 값처럼 사용하지 않는다.
# - 기존 ROS/Nav2 기능과 공통 모듈을 재사용하고 같은 기능을 중복 구현하지 않는다.
# - 요청하지 않은 패키지, 외부 서버, DB, 플러그인 구조는 추가하지 않는다.
# - 단순한 기능을 불필요한 클래스 계층이나 여러 보조 파일로 나누지 않는다.
# - 필요한 입력 검사와 안전 처리는 구현하되 자동 복구 기능을 임의로 확대하지 않는다.
# - 이 파일의 완료 기준을 만족하면 추가 기능 구현을 멈춘다.
#
# [역할]
# 부우의 관측과 게임 상태를 받아 행동을 실행하는 ROS 노드.
# [입출력]
# 입력: 직접 관측, 웹캠 제보, 부우 자신의 위치, 게임·안전 상태, 레벨 설정.
# 출력: BooState와 Nav2 목표 요청.
# [구현]
# 관측 출처와 유효성을 확인해 boo_fsm.py에 전달한다.
# 결정된 행동을 nav2_client.py로 실행하고 성공·실패 결과를 FSM에 반영한다.
# 동일한 목표를 매 주기마다 다시 보내지 않는다.
# [실패 처리]
# 게임 중단·이동 금지 시 진행 중인 목표를 취소한다.
# 목표 실패와 탐지 상실을 정상 도착이나 지속 탐지로 취급하지 않는다.
# [범위]
# 지도 표시용 펌킨 위치를 항상 아는 것처럼 추격하지 않는다.
# 게임 승패 판정·경로 계획·최종 안전 속도 처리를 중복 구현하지 않는다.
# [완료 기준]
# 직접 탐지와 웹캠 제보가 구분되고 탐지 상실·목표 실패·게임 중단이 처리된다.
