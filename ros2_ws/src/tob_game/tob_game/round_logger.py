# TrickOrBot 구현 지침 v2
# [공통 구현 원칙]
# - 아래 내용은 구현할 기능의 설명이며, 현재 기능이 구현되어 있다는 뜻은 아니다.
# - ROS 2 Jazzy와 현재 패키지 구조를 기준으로 최소한의 구현을 작성한다.
# - docs/interfaces.md와 관련 .msg/.srv 파일을 확인하고 공통 규격을 따른다.
# - 필수 규격이나 게임 규칙이 미정이면 필요한 결정 사항을 먼저 명시한다.
# - 미정인 값을 실제 장비에서 확인한 값처럼 사용하지 않는다.
# - 기존 ROS/Nav2 기능과 공통 모듈을 재사용하고 같은 기능을 중복 구현하지 않는다.
# - 요청하지 않은 패키지, 외부 서버, DB, 플러그인 구조는 추가하지 않는다.
# - 단순한 기능을 불필요한 클래스 계층이나 여러 보조 파일로 나누지 않는다.
# - 필요한 입력 검사와 안전 처리는 구현하되 자동 복구 기능을 임의로 확대하지 않는다.
# - 이 파일의 완료 기준을 만족하면 추가 기능 구현을 멈춘다.
#
# [역할]
# 회차 결과와 필요한 운영 사건을 JSONL 파일에 기록하는 일반 Python 모듈.
# [입출력]
# 입력: game_manager가 전달한 회차 결과·사건. 출력: 한 줄당 하나의 JSON 기록.
# [구현]
# 회차 ID, 레벨, 시각, 결과, 사탕 수, 개입·안전 정지 횟수, 배터리 등 합의된 항목을 기록한다.
# game_manager가 회차 종료를 한 번 호출하도록 하고 해당 결과를 저장한다.
# 저장 위치는 설정으로 받으며 소스 코드나 설치 폴더에 기록하지 않는다.
# [실패 처리]
# 디렉터리 생성·파일 쓰기 실패를 숨기지 않고 호출자에게 알린다.
# [범위]
# 순위 DB와 닉네임 처리는 기존 백엔드가 담당한다.
# 별도 DB, 메시지 큐, 이벤트 재생 서버, 자동 업로드 시스템은 만들지 않는다.
# [완료 기준]
# 저장한 줄을 JSON으로 읽을 수 있고 필수 운영 항목과 회차 ID가 존재한다.
