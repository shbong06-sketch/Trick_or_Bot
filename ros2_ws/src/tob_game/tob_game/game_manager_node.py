# TrickOrBot 구현 지침 v2
# [공통 구현 원칙]
# - 아래 내용은 구현할 기능의 설명이며, 현재 기능이 구현되어 있다는 뜻은 아니다.
# - ROS 2 Jazzy와 현재 패키지 구조를 기준으로 최소한의 구현을 작성한다.
# - docs/interfaces.md와 관련 .msg/.srv 파일을 확인하고 공통 규격을 따른다.
# - 필수 규격이나 게임 규칙이 미정이면 필요한 결정 사항을 먼저 명시한다.
# - 미정인 값을 실제 장비에서 확인한 값처럼 사용하지 않는다.
# - 기존 ROS/Nav2 기능과 공통 모듈을 재사용하고 같은 기능을 중복 구현하지 않는다.
# - 요청하지 않은 패키지, 외부 서버, DB, 플러그인 구조는 추가하지 않는다.
# - 단순한 기능을 불필요한 클래스 계층이나 여러 보조 파일로 나누지 않는다.
# - 필요한 입력 검사와 안전 처리는 구현하되 자동 복구 기능을 임의로 확대하지 않는다.
# - 이 파일의 완료 기준을 만족하면 추가 기능 구현을 멈춘다.
#
# [역할]
# 회차 상태를 관리하고 사탕·체포·탈출·승패의 최종 결과를 결정하는 ROS 노드.
# [입출력]
# 입력: 게임 명령, 로봇 위치, 펌킨 관측, 안전 상태, 선택한 레벨 설정.
# 출력: GameState, GameEvent와 제어 노드가 사용할 게임 진행 상태.
# [구현]
# 시작 조건을 검사하고 회차 상태를 전환한다.
# 판정 계산은 rules.py, 설정 읽기는 level_loader.py, 기록은 round_logger.py에 맡긴다.
# 종료는 회차별로 한 번 처리하고 새 회차 시작 시 이전 판정 상태를 초기화한다.
# [실패 처리]
# 필수 위치·관측이 유효하지 않으면 이를 사용한 획득·체포 판정을 하지 않는다.
# 시작 조건 미충족은 사유와 함께 거절한다. 실행 중 중단 정책은 공통 명세를 따른다.
# [범위]
# 영상 추론, Nav2 목표 관리, 최종 속도 발행을 직접 구현하지 않는다.
# [완료 기준]
# 시작·진행·종료·초기화가 동작하고 같은 사건이나 종료가 중복 처리되지 않는다.
