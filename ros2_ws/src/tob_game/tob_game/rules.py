# TrickOrBot 구현 지침 v2
# [공통 구현 원칙]
# - 아래 내용은 구현할 기능의 설명이며, 현재 기능이 구현되어 있다는 뜻은 아니다.
# - ROS 2 Jazzy와 현재 패키지 구조를 기준으로 최소한의 구현을 작성한다.
# - docs/interfaces.md와 관련 .msg/.srv 파일을 확인하고 공통 규격을 따른다.
# - 필수 규격이나 게임 규칙이 미정이면 필요한 결정 사항을 먼저 명시한다.
# - 미정인 값을 실제 장비에서 확인한 값처럼 사용하지 않는다.
# - 기존 ROS/Nav2 기능과 공통 모듈을 재사용하고 같은 기능을 중복 구현하지 않는다.
# - 요청하지 않은 패키지, 외부 서버, DB, 플러그인 구조는 추가하지 않는다.
# - 단순한 기능을 불필요한 클래스 계층이나 여러 보조 파일로 나누지 않는다.
# - 필요한 입력 검사와 안전 처리는 구현하되 자동 복구 기능을 임의로 확대하지 않는다.
# - 이 파일의 완료 기준을 만족하면 추가 기능 구현을 멈춘다.
#
# [역할]
# 사탕 획득, 구역 체류, 체포, 탈출, 시간 초과를 계산하는 일반 Python 모듈.
# [입출력]
# 입력: 위치, 유효한 관측, 현재 게임 상태, 경과 시간, 레벨 기준값.
# 출력: 판정 결과와 필요한 상태 변경 정보.
# [구현]
# 거리와 체류 시간을 검사하고 이미 획득한 사탕의 중복 획득을 막는다.
# 연속 탐지는 미탐지 또는 관측 만료 시 연속성을 끊는다.
# 체포와 탈출이 동시에 가능한 경우의 우선순위는 공통 게임 규칙을 따른다.
# [실패 처리]
# 유효하지 않은 위치나 시간을 정상 판정에 사용하지 않는다.
# [범위]
# ROS 통신·DB·실제 시계 읽기를 넣지 않고 필요한 시간은 호출자가 전달한다.
# 체포 시 즉시 종료인지 하트 감소인지, 일시정지 중 시간 처리는 임의로 정하지 않는다.
# [완료 기준]
# 획득 중복 방지, 구역 이탈, 탐지 끊김, 경계값에서 합의된 결과를 반환한다.
